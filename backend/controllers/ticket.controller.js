// Generate a new event ticket
exports.generateTicket = async (req, res, next) => {
  try {
    const { eventId } = req.body;
    const userId = req.user.id;

    const event = await Event.findById(eventId);
    if (!event) return res.status(404).json({ message: "Event not found" });

    const registered = await RegistrationResponse.findOne({ eventId, userId });
    if (!registered)
      return res.status(403).json({ message: "User not registered for this event" });

    const existing = await Ticket.findOne({ eventId, userId });
    if (existing) {
      return res.json({
        success: true,
        ticket: existing,
        message: "Ticket already exists",
      });
    }

    const token = generateToken(32);
    const qrContent = JSON.stringify({
      ticketId: token,
      eventId,
      userId,
      type: "event-ticket",
    });

    const qrCode = await QRCode.toDataURL(qrContent);

    const ticket = await Ticket.create({
      eventId,
      userId,
      qrCode,
      token,
      status: 'active',
    });

    res.status(201).json({
      success: true,
      ticket,
      message: "Ticket generated successfully",
    });
  } catch (error) {
    console.error("Ticket generation error:", error);
    return next(error);
  }
};

// Generate tickets in bulk (admin only)
exports.generateBulkTickets = async (req, res, next) => {
  try {
    const { eventId, userIds, sendEmail = true } = req.body;

    const event = await Event.findById(eventId);
    if (!event) return res.status(404).json({ message: "Event not found" });

    const results = [];
    
    for (const userId of userIds) {
      try {
        // Check if user is registered for the event
        const registered = await RegistrationResponse.findOne({ eventId, userId });
        if (!registered) {
          results.push({
            userId,
            success: false,
            error: "User not registered for this event"
          });
          continue;
        }

        // Check if ticket already exists
        const existing = await Ticket.findOne({ eventId, userId });
        if (existing) {
          results.push({
            userId,
            success: false,
            error: "Ticket already exists",
            ticket: existing
          });
          continue;
        }

        // Generate ticket
        const token = generateToken(32);
        const qrContent = JSON.stringify({
          ticketId: token,
          eventId,
          userId,
          type: "event-ticket",
        });

        const qrCode = await QRCode.toDataURL(qrContent);

        const ticket = await Ticket.create({
          eventId,
          userId,
          qrCode,
          token,
          status: 'active',
          autoGenerated: true,
        });

        // Send email if requested
        if (sendEmail) {
          try {
            const user = await User.findById(userId);
            await exports.sendTicketEmail(ticket, user, event);
          } catch (emailError) {
            console.error(`Failed to send email to user ${userId}:`, emailError);
            // Continue even if email fails
          }
        }

        results.push({
          userId,
          success: true,
          ticket,
          message: sendEmail ? "Ticket generated and email sent" : "Ticket generated"
        });

      } catch (error) {
        results.push({
          userId,
          success: false,
          error: error.message
        });
      }
    }

    const successful = results.filter(r => r.success).length;
    const failed = results.filter(r => !r.success).length;

    res.json({
      success: true,
      results,
      message: `Generated ${successful} tickets successfully, ${failed} failed`
    });
  } catch (error) {
    console.error("Bulk ticket generation error:", error);
    return next(error);
  }
};

// Approve pending tickets (admin only)
exports.approvePendingTickets = async (req, res, next) => {
  try {
    const { ticketIds } = req.body;

    const tickets = await Ticket.find({ 
      _id: { $in: ticketIds },
      status: 'pending' 
    }).populate('userId').populate('eventId');

    const results = [];
    
    for (const ticket of tickets) {
      try {
        await this.sendTicketEmail(ticket, ticket.userId, ticket.eventId);
        ticket.status = 'active';
        await ticket.save();
        
        results.push({
          ticketId: ticket._id,
          success: true,
          message: `Ticket approved and email sent to ${ticket.userId.email}`
        });
      } catch (error) {
        results.push({
          ticketId: ticket._id,
          success: false,
          error: error.message
        });
      }
    }

    const successful = results.filter(r => r.success).length;

    res.json({
      success: true,
      results,
      message: `Approved ${successful} tickets successfully`
    });
  } catch (error) {
    console.error("Approve pending tickets error:", error);
    return next(error);
  }
};

