// Get all scanned tickets for an event (admin)
exports.getEventScannedTickets = async (req, res, next) => {
  try {
    const { eventId } = req.params;
    const { page = 1, limit = 50, status } = req.query;

    let query = { eventId };
    
    // Filter by status
    if (status === 'checkedIn') {
      query.checkedIn = true;
      query.checkOutTime = { $exists: false };
    } else if (status === 'checkedOut') {
      query.checkOutTime = { $exists: true };
    } else if (status === 'notCheckedIn') {
      query.checkedIn = false;
    }

    const tickets = await Ticket.find(query)
      .populate("userId", "firstName lastName email profile")
      .sort({ checkInTime: -1, createdAt: -1 })
      .limit(parseInt(limit))
      .skip((parseInt(page) - 1) * parseInt(limit));

    const total = await Ticket.countDocuments(query);

    res.json({
      success: true,
      tickets,
      pagination: {
        page: parseInt(page),
        limit: parseInt(limit),
        total,
        pages: Math.ceil(total / parseInt(limit))
      }
    });
  } catch (error) {
    console.error("Get event scanned tickets error:", error);
    return next(error);
  }
};

