// Get scan statistics for an event with time ranges
exports.getEventScanStats = async (req, res) => {
  try {
    const { eventId } = req.params;
    const { timeRange = 'all' } = req.query;

    let dateFilter = {};
    const now = new Date();

    switch (timeRange) {
      case '1d':
        dateFilter = { 
          $gte: new Date(now.getTime() - 24 * 60 * 60 * 1000) 
        };
        break;
      case '7d':
        dateFilter = { 
          $gte: new Date(now.getTime() - 7 * 24 * 60 * 60 * 1000) 
        };
        break;
      case '30d':
        dateFilter = { 
          $gte: new Date(now.getTime() - 30 * 24 * 60 * 60 * 1000) 
        };
        break;
      // 'all' - no date filter
    }

    const totalTickets = await Ticket.countDocuments({ eventId });
    const checkedInTickets = await Ticket.countDocuments({ 
      eventId, 
      checkedIn: true 
    });
    const checkedOutTickets = await Ticket.countDocuments({ 
      eventId, 
      checkOutTime: { $exists: true } 
    });

    // Get hourly check-in data
    const hourlyData = await Ticket.aggregate([
      {
        $match: {
          eventId: new mongoose.Types.ObjectId(eventId),
          checkInTime: dateFilter
        }
      },
      {
        $group: {
          _id: {
            hour: { $hour: "$checkInTime" },
            date: { $dateToString: { format: "%Y-%m-%d", date: "$checkInTime" } }
          },
          count: { $sum: 1 }
        }
      },
      {
        $sort: { "_id.date": 1, "_id.hour": 1 }
      }
    ]);

    // Calculate peak hours
    const peakHours = hourlyData
      .map(item => ({
        hour: item._id.hour,
        count: item.count,
        percentage: (item.count / checkedInTickets) * 100
      }))
      .sort((a, b) => b.count - a.count)
      .slice(0, 5);

    // Get daily data for charts
    const dailyData = await Ticket.aggregate([
      {
        $match: {
          eventId: new mongoose.Types.ObjectId(eventId),
          $or: [
            { checkInTime: { $exists: true } },
            { checkOutTime: { $exists: true } }
          ]
        }
      },
      {
        $group: {
          _id: {
            date: { $dateToString: { format: "%Y-%m-%d", date: "$checkInTime" } }
          },
          checkIns: {
            $sum: { $cond: [{ $ne: ["$checkInTime", null] }, 1, 0] }
          },
          checkOuts: {
            $sum: { $cond: [{ $ne: ["$checkOutTime", null] }, 1, 0] }
          }
        }
      },
      {
        $sort: { "_id.date": 1 }
      }
    ]);

    res.json({
      success: true,
      stats: {
        totalTickets,
        checkedInTickets,
        checkedOutTickets,
        attendanceRate: totalTickets > 0 ? (checkedInTickets / totalTickets) * 100 : 0,
        hourlyData,
        peakHours,
        dailyData: dailyData.map(item => ({
          date: item._id.date,
          checkIns: item.checkIns,
          checkOuts: item.checkOuts
        }))
      }
    });
  } catch (error) {
    console.error("Get scan stats error:", error);
    res.status(500).json({ success: false, message: error.message });
  }
};

