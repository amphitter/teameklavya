// Scan ticket (admin entry/exit) - ENHANCED
exports.scanTicket = async (req, res, next) => {
  try {
    const { token, action } = req.body;
    const scannedBy = req.user.id;

    if (!["entry", "exit"].includes(action)) {
      return res.status(400).json({ message: "Invalid action. Use 'entry' or 'exit'" });
    }

    const ticket = await Ticket.findOne({ token })
      .populate("eventId", "title startDate endDate venue")
      .populate("userId", "firstName lastName email profile");

    if (!ticket) {
      return res.status(404).json({ 
        success: false,
        message: "Invalid ticket token" 
      });
    }

    // Check if ticket is active
    if (ticket.status !== 'active') {
      return res.status(400).json({ 
        success: false,
        message: "Ticket is not active"
      });
    }

    const now = new Date();
    const eventStart = new Date(ticket.eventId.startDate);
    const eventEnd = new Date(ticket.eventId.endDate);

    // Check if event has started
    if (now < eventStart) {
      return res.status(400).json({ 
        success: false,
        message: "Event hasn't started yet" 
      });
    }

    // Check if event has ended (allow check-out after event end)
    if (action === "entry" && now > eventEnd) {
      return res.status(400).json({ 
        success: false,
        message: "Event has already ended" 
      });
    }

    if (action === "entry") {
      if (ticket.checkedIn) {
        return res.status(400).json({ 
          success: false,
          message: "Already checked in",
          ticket 
        });
      }
      ticket.checkedIn = true;
      ticket.checkInTime = now;
      ticket.scanMethod = req.body.scanMethod || 'qr';
      ticket.deviceType = req.body.deviceType || 'web';
      ticket.entryLogs.push({ 
        action: "entry", 
        timestamp: now, 
        scannedBy,
        scanMethod: req.body.scanMethod,
        deviceType: req.body.deviceType
      });
      
    } else if (action === "exit") {
      if (!ticket.checkedIn) {
        return res.status(400).json({ 
          success: false,
          message: "Not checked in yet",
          ticket 
        });
      }
      if (ticket.checkOutTime) {
        return res.status(400).json({ 
          success: false,
          message: "Already checked out",
          ticket 
        });
      }
      ticket.checkOutTime = now;
      ticket.scanMethod = req.body.scanMethod || 'qr';
      ticket.deviceType = req.body.deviceType || 'web';
      ticket.entryLogs.push({ 
        action: "exit", 
        timestamp: now, 
        scannedBy,
        scanMethod: req.body.scanMethod,
        deviceType: req.body.deviceType
      });
    }

    await ticket.save();

    // Populate the updated ticket for response
    const updatedTicket = await Ticket.findById(ticket._id)
      .populate("eventId", "title startDate endDate venue")
      .populate("userId", "firstName lastName email profile");

    res.json({
      success: true,
      message: `${action === "entry" ? "Check-in" : "Check-out"} successful`,
      ticket: updatedTicket,
    });
  } catch (error) {
    console.error("Ticket scan error:", error);
    return next(error);
  }
};

